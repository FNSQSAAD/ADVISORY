/* Builds js/finance-core.js by lifting the DOM-free math out of js/calculators.js
   verbatim, so the chatbot and the calculators page can never drift apart.
   calculators.js itself is left untouched - it is live and working - and
   tools/parity-test.js proves the two copies still agree.
   Run: node tools/build-finance-core.js                                        */
const fs = require('fs');
const path = require('path');
const SRC = path.join(__dirname, '..', 'js', 'calculators.js');
const OUT = path.join(__dirname, '..', 'js', 'finance-core.js');

const L = fs.readFileSync(SRC, 'utf8').split(/\r?\n/);
const cut = (a, b) => L.slice(a - 1, b).join('\n');   // 1-indexed, inclusive

/* Locate blocks by their declaration line rather than hard-coded numbers, so an
   edit to calculators.js shifts the slice instead of silently truncating it. */
function lineOf(re, from) {
  for (let i = (from || 1) - 1; i < L.length; i++) if (re.test(L[i])) return i + 1;
  throw new Error('build-finance-core: could not find ' + re);
}
function blockEnd(start) {            // first line that is exactly '}' or '};'
  for (let i = start; i < L.length; i++) if (/^\};?\s*$/.test(L[i])) return i + 1;
  throw new Error('build-finance-core: unterminated block at ' + start);
}

const pick = re => { const s = lineOf(re); return cut(s, blockEnd(s)); };

const blocks = [
  pick(/^\/\* Amortising repayment/),        // comment line precedes the fn
  pick(/^function principalFor/),
  pick(/^function termText/),
  pick(/^function simulate/),
  pick(/^function incomeTax/),
  pick(/^function netMonthly/),
  pick(/^function hemMonthly/),
  pick(/^function lmiEstimate/),
  pick(/^var DUTY = \{/),
  pick(/^var REGISTRY = \{/)
];
// the repayment slice starts at its comment, so pull the function body too
blocks[0] = (() => { const s = lineOf(/^function repayment/); return cut(s, blockEnd(s)); })();

const banner = `/* GENERATED by tools/build-finance-core.js - do not edit by hand.
   Source of truth: js/calculators.js (the live calculators page).
   Regenerate:  node tools/build-finance-core.js
   Verify:      node tools/parity-test.js

   Pure, DOM-free Australian mortgage math shared by the calculators page and the
   Finance Square chatbot, so a number quoted in chat always equals the number the
   calculator on the page produces. Loads in the browser (window.FNSQFinance) and
   in Node (module.exports) alike. */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.FNSQFinance = factory();
}(typeof self !== 'undefined' ? self : this, function () {
'use strict';

function money(n)  { return '$' + Math.round(n || 0).toLocaleString('en-AU'); }
function pct(n)    { return (Math.round((n || 0) * 100) / 100).toFixed(2) + '%'; }
function clamp(v, lo, hi) { return Math.max(lo, Math.min(hi, v)); }
var PER_YEAR = { weekly: 52, fortnightly: 26, monthly: 12, quarterly: 4, annually: 1 };

/* ---------- lifted verbatim from js/calculators.js ---------- */
`;

/* Headless equivalents of the two page calculators the bot quotes most. The page
   versions (calcBorrowing / calcDuty) read the DOM; these take a plain object and
   return numbers, but run the identical formulas above. */
const api = `
/* ---------- headless equivalents of the page calculators ---------- */

/* Mirrors calcBorrowing(): net income after ATO tax, HEM expense floor, credit
   limits at 3.8%/month, and the APRA 3.00pp serviceability buffer. */
function borrowingCapacity(o) {
  o = o || {};
  var applicants = o.applicants === 2 ? 2 : 1;
  var deps  = o.dependants || 0;
  var rate  = o.rate > 0 ? o.rate : 6.24;
  var years = clamp(o.years || 30, 5, 30);
  var assessRate = rate + 3.00;

  var netInc = netMonthly(o.income1 || 0) + netMonthly(o.income2 || 0) + netMonthly(o.otherIncome || 0);
  var rentMonthly = o.purpose === 'investment' ? (o.rentWeekly || 0) * 52 / 12 * 0.80 : 0;

  var hem = hemMonthly(applicants, deps);
  var usedExpenses = Math.max(o.expenses || 0, hem);
  var cardCommit = (o.cardLimits || 0) * 0.038;
  var commitments = cardCommit + (o.carLoan || 0) + (o.otherRepayments || 0);

  var surplus = netInc + rentMonthly - usedExpenses - commitments;
  var maxLoan = surplus > 0 ? principalFor(surplus, assessRate, years * 12, 12) : 0;
  maxLoan = clamp(maxLoan, 0, 8000000);

  var deposit = o.deposit || 0;
  var price = Math.max(0, (maxLoan + deposit) / 1.05);
  var costs = price * 0.05;
  var depositToLoan = Math.max(0, deposit - costs);
  var loanUsed = clamp(price - depositToLoan, 0, maxLoan);
  var lvr = price > 0 ? clamp(loanUsed / price * 100, 0, 100) : 0;

  return {
    maxLoan: maxLoan,
    low:  Math.round(maxLoan * 0.95 / 5000) * 5000,
    high: Math.round(maxLoan * 1.05 / 5000) * 5000,
    price: price,
    surplus: Math.max(0, surplus),
    assessRate: assessRate,
    rate: rate,
    years: years,
    monthlyRepayment: maxLoan > 0 ? repayment(maxLoan, rate, years * 12, 12) : 0,
    lvr: lvr,
    lmi: lmiEstimate(loanUsed, lvr),
    benchmarkExpenses: usedExpenses,
    hemApplied: usedExpenses > (o.expenses || 0),
    commitments: commitments,
    cardCommitment: cardCommit
  };
}

/* Mirrors calcDuty(): duty + transfer + mortgage registration, and the LMI and
   cash-needed figures the upfront-costs panel shows. */
function stampDuty(o) {
  o = o || {};
  var state = String(o.state || 'VIC').toUpperCase();
  if (!DUTY[state]) return null;
  var v = o.value || 0;
  var use = o.use === 'investment' ? 'investment' : 'home';
  var fhb = use === 'investment' ? false : !!o.firstHomeBuyer;

  var res = DUTY[state](v, { use: use, fhb: fhb, build: o.build || 'existing' });
  var duty = Math.max(0, res.duty);
  var reg = REGISTRY[state];
  var transferFee = reg.transfer(v);
  var mortgageFee = reg.mortgage;

  var deposit = o.deposit || 0;
  var loan = Math.max(0, v - deposit);
  var lvr = v > 0 ? loan / v * 100 : 0;
  var lmi = lmiEstimate(loan, lvr);
  var legals = o.legals == null ? 2000 : o.legals;
  var govt = duty + transferFee + mortgageFee;

  return {
    state: state, value: v, duty: duty, note: res.note,
    effectiveRate: v > 0 ? duty / v * 100 : 0,
    transferFee: transferFee, mortgageFee: mortgageFee, government: govt,
    lmi: lmi, legals: legals, upfront: govt + lmi + legals,
    cashNeeded: deposit + govt + legals,
    loan: loan, lvr: lvr, firstHomeBuyer: fhb
  };
}

/* Repayments for a plain loan, at any repayment frequency. */
function loanRepayments(o) {
  o = o || {};
  var P = o.amount || 0;
  var rate = o.rate > 0 ? o.rate : 6.24;
  var years = o.years || 30;
  var perYear = PER_YEAR[o.frequency] || 12;
  var periods = Math.round(years * perYear);
  var pay = P > 0 ? repayment(P, rate, periods, perYear) : 0;
  var monthly = P > 0 ? repayment(P, rate, years * 12, 12) : 0;
  var totalPaid = pay * periods;
  return {
    amount: P, rate: rate, years: years, frequency: o.frequency || 'monthly',
    perYear: perYear, payment: pay, monthly: monthly,
    totalPaid: totalPaid, totalInterest: Math.max(0, totalPaid - P),
    interestOnly: P * rate / 100 / 12
  };
}

/* What extra repayments or a lump sum do to the term and the interest bill. */
function extraRepayments(o) {
  o = o || {};
  var P = o.amount || 0;
  var rate = o.rate > 0 ? o.rate : 6.24;
  var years = o.years || 30;
  var base = repayment(P, rate, years * 12, 12);
  var a = simulate(P, rate, base, {});
  var b = simulate(P, rate, base, {
    extraMonthly: o.extraMonthly || 0,
    lumpAmount: o.lumpAmount || 0,
    lumpAfterMonths: o.lumpAfterMonths || 0
  });
  return {
    baseMonthly: base,
    baseMonths: a.months, baseInterest: a.totalInterest,
    newMonths: b.months, newInterest: b.totalInterest,
    monthsSaved: a.months - b.months,
    interestSaved: a.totalInterest - b.totalInterest
  };
}

return {
  money: money, pct: pct, termText: termText,
  repayment: repayment, principalFor: principalFor, simulate: simulate,
  incomeTax: incomeTax, netMonthly: netMonthly, hemMonthly: hemMonthly,
  lmiEstimate: lmiEstimate,
  DUTY: DUTY, REGISTRY: REGISTRY, STATES: Object.keys(DUTY),
  borrowingCapacity: borrowingCapacity,
  stampDuty: stampDuty,
  loanRepayments: loanRepayments,
  extraRepayments: extraRepayments
};
}));
`;

fs.writeFileSync(OUT, banner + blocks.join('\n\n') + '\n' + api);
console.log('wrote js/finance-core.js (' + (banner + blocks.join('\n\n') + api).length + ' bytes)');
